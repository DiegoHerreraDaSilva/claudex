let lang = "pt";

export function getLang() {
  return lang;
}

export function t(key, params) {
  const dict = I18N[lang] ?? I18N.en;
  let value = dict[key] ?? I18N.en[key] ?? key;
  if (params)
    for (const [k, v] of Object.entries(params)) value = value.split(`{${k}}`).join(String(v));
  return value;
}

export function roleLabel(role) {
  const map = {
    user: "roleUser",
    assistant: "roleAssistant",
    tool: "roleTool",
    result: "roleResult",
    routing: "roleRouting",
    error: "roleError",
    system: "roleSystem",
  };
  return t(map[role] ?? "roleSystem");
}

export function setLang(next) {
  lang = next === "en" ? "en" : "pt";
  try {
    localStorage.setItem(LANG_KEY, lang);
  } catch {
    /* ignore */
  }
  applyStatic();
}

export function initLang() {
  try {
    lang = localStorage.getItem(LANG_KEY) === "en" ? "en" : "pt";
  } catch {
    lang = "pt";
  }
}

export function applyStatic(root = document) {
  document.documentElement.lang = lang === "pt" ? "pt-BR" : "en";
  root.querySelectorAll("[data-i18n]").forEach((node) => {
    node.textContent = t(node.dataset.i18n);
  });
  root.querySelectorAll("[data-i18n-ph]").forEach((node) => {
    node.placeholder = t(node.dataset.i18nPh);
  });
}
